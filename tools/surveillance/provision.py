#!/usr/bin/env python3
"""Create private receiver credentials and the optional firmware profile."""

from __future__ import annotations

import argparse
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import venv
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
PROFILE_PATH = REPO_ROOT / "firmware/main/apps/app_surveillance/connection_profile.h"


def lan_ipv4() -> str:
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("192.0.2.1", 9))
        return probe.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        probe.close()


def run_checked(args: list[str], cwd: Path | None = None) -> None:
    subprocess.run(args, cwd=cwd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def cpp_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write_profile(profile: Path, token: str, ca_pem: str, host: str, port: int) -> None:
    profile.parent.mkdir(parents=True, exist_ok=True)
    content = f'''#pragma once
// Generated by tools/surveillance/provision.py. Keep private and out of version control.
#define SURVEILLANCE_PROFILE_CONFIGURED 1
static constexpr const char kSurveillanceReceiverHost[] = "{host}";
static constexpr int kSurveillanceReceiverPort = {port};
static constexpr const char kSurveillancePairingToken[] = "{token}";
static constexpr const char kSurveillanceCaPem[] = {cpp_string(ca_pem)};
'''
    fd = os.open(profile, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as output:
        output.write(content)
    try:
        profile.chmod(0o600)
    except OSError:
        pass


def install_service(config_dir: Path, data_dir: Path) -> None:
    app_dir = data_dir / "receiver"
    app_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(HERE / "receiver.py", app_dir / "receiver.py")
    shutil.copy2(HERE / "requirements.txt", app_dir / "requirements.txt")
    venv_dir = app_dir / ".venv"
    if not venv_dir.exists():
        venv.EnvBuilder(with_pip=True).create(venv_dir)
    python = venv_dir / "bin/python"
    subprocess.run([str(python), "-m", "pip", "install", "-r", str(app_dir / "requirements.txt")], check=True)

    unit_dir = Path.home() / ".config/systemd/user"
    unit_dir.mkdir(parents=True, exist_ok=True)
    unit = f'''[Unit]
Description=StackChan local surveillance receiver
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=%h/.local/share/stackchan-surveillance/receiver
ExecStart=%h/.local/share/stackchan-surveillance/receiver/.venv/bin/python %h/.local/share/stackchan-surveillance/receiver/receiver.py --config %h/.config/stackchan-surveillance/receiver.json
Restart=always
RestartSec=3
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=%h/.local/share/stackchan-surveillance
PrivateTmp=true
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=default.target
'''
    unit_path = unit_dir / "stackchan-surveillance.service"
    unit_path.write_text(unit, encoding="utf-8")
    unit_path.chmod(0o600)
    subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
    subprocess.run(["systemctl", "--user", "enable", "--now", "stackchan-surveillance.service"], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-dir", type=Path, default=Path.home() / ".config/stackchan-surveillance")
    parser.add_argument("--data-dir", type=Path, default=Path.home() / ".local/share/stackchan-surveillance")
    parser.add_argument("--profile", type=Path, default=PROFILE_PATH)
    parser.add_argument("--install-service", action="store_true", help="install dependencies and enable the user service")
    args = parser.parse_args()
    if shutil.which("openssl") is None:
        parser.error("openssl is required to create the local CA and TLS certificate")
    args.config_dir.mkdir(parents=True, exist_ok=True)
    args.data_dir.mkdir(parents=True, exist_ok=True)
    try:
        args.config_dir.chmod(0o700)
        args.data_dir.chmod(0o700)
    except OSError:
        pass

    ca_key = args.config_dir / "receiver-ca.key"
    ca_cert = args.config_dir / "receiver-ca.pem"
    server_key = args.config_dir / "receiver.key"
    server_csr = args.config_dir / "receiver.csr"
    server_cert = args.config_dir / "receiver.pem"
    extension = args.config_dir / "receiver.ext"
    if not ca_key.exists() and not ca_cert.exists():
        run_checked(["openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", str(ca_key)])
        run_checked(["openssl", "req", "-x509", "-new", "-sha256", "-days", "3650", "-key", str(ca_key),
                     "-subj", "/CN=StackChan Surveillance Local CA",
                     "-addext", "basicConstraints=critical,CA:TRUE",
                     "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", str(ca_cert)])
    if not server_key.exists() and not server_cert.exists():
        extension.write_text(
            "subjectAltName=DNS:stackchan-surveillance.local,DNS:localhost,IP:127.0.0.1\n"
            "extendedKeyUsage=serverAuth\nkeyUsage=digitalSignature,keyEncipherment\n",
            encoding="utf-8",
        )
        run_checked(["openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", str(server_key)])
        run_checked(["openssl", "req", "-new", "-key", str(server_key), "-subj", "/CN=stackchan-surveillance.local",
                     "-out", str(server_csr)])
        run_checked(["openssl", "x509", "-req", "-sha256", "-days", "825", "-in", str(server_csr),
                     "-CA", str(ca_cert), "-CAkey", str(ca_key), "-CAcreateserial", "-extfile", str(extension),
                     "-out", str(server_cert)])
    for private_path in (ca_key, server_key):
        try:
            private_path.chmod(0o600)
        except OSError:
            pass
    token_path = args.config_dir / "pairing-token"
    if token_path.exists():
        token = token_path.read_text(encoding="ascii").strip()
    else:
        token = secrets.token_urlsafe(32)
        token_path.write_text(token + "\n", encoding="ascii")
        token_path.chmod(0o600)

    config = {
        "pairing_token": token,
        "certificate": str(server_cert),
        "private_key": str(server_key),
        "data_dir": str(args.data_dir),
    }
    config_path = args.config_dir / "receiver.json"
    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    config_path.chmod(0o600)
    write_profile(args.profile, token, ca_cert.read_text(encoding="ascii"), "stackchan-surveillance.local", 8443)
    if args.install_service:
        install_service(args.config_dir, args.data_dir)
    print(f"Private receiver configuration: {config_path}")
    print(f"Firmware profile generated: {args.profile}")
    print("Stable mDNS address: https://stackchan-surveillance.local:8443")
    print(f"Receiver LAN address announced at run time: {lan_ipv4()}")
    if args.install_service:
        print("User service installed and enabled; local gallery: http://127.0.0.1:8765")
    else:
        print("To install the restartable user service, rerun with --install-service.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except subprocess.CalledProcessError as exc:
        print(f"provisioning command failed: {exc.cmd[0]} (details omitted)", file=sys.stderr)
        raise SystemExit(1)
